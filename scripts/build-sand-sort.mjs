import { readFileSync, writeFileSync } from 'node:fs';
const gameRoot = new URL('../games/puzzle/sand-sort/', import.meta.url);
const files = ['sand-sort-rules.mjs', 'sand-sort-levels.mjs', 'sand-sort-session.mjs', 'sand-sort-physics.mjs', 'sand-sort-renderer.mjs', 'sand-sort-game.mjs'];
let three = readFileSync(new URL('../assets/vendor/three.module.r160.js', import.meta.url), 'utf8');
const sources = files.map(file => readFileSync(new URL(file, gameRoot), 'utf8'));
const names = [...new Set(sources.join('\n').matchAll(/THREE\.([A-Za-z_][A-Za-z_0-9]*)/g))].map(match => match[1]);
const uniqueNames = [...new Set(names)].sort();
const exportLine = /\nexport \{[^\n]+\};\s*$/;
if (!three.includes('SPDX-License-Identifier: MIT') || !exportLine.test(three)) throw new Error('Unsupported Three.js source');
three = three.replace(exportLine, `\nconst THREE = { ${uniqueNames.join(', ')} };\n`);
const backdrop = readFileSync(new URL('assets/studio-backdrop-faithful.png', gameRoot));
const grains = readFileSync(new URL('assets/sand-grain-relief.png', gameRoot));
const glassDetail = readFileSync(new URL('assets/glass-reflection-detail.png', gameRoot));
const code = sources.map(source => source
  .replace(/^import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];\r?\n/gm, '')
  .replace(/^export\s*\{[^}]+\}\s*from\s*['"][^'"]+['"];\r?\n/gm, '')
  .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, '')
  .replace("'./assets/studio-backdrop-faithful.png'", JSON.stringify(`data:image/png;base64,${backdrop.toString('base64')}`))
  .replace("'./assets/sand-grain-relief.png'", JSON.stringify(`data:image/png;base64,${grains.toString('base64')}`))
  .replace("'./assets/glass-reflection-detail.png'", JSON.stringify(`data:image/png;base64,${glassDetail.toString('base64')}`)))
  .join('\n');
const bundle = `/* Generated by node scripts/build-sand-sort.mjs. Three.js r160, MIT license retained below. */\n(function () {\n'use strict';\n${three}\n${code}\n})();\n`;
writeFileSync(new URL('sand-sort.bundle.js', gameRoot), bundle, 'utf8');
console.log(`Built sand-sort.bundle.js (${(bundle.length / 1024 / 1024).toFixed(2)} MB). Local file URLs supported.`);
