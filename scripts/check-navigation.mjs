import assert from 'node:assert/strict';
import {readFile, access} from 'node:fs/promises';
import vm from 'node:vm';

const context = {window:{}, URLSearchParams};
vm.runInNewContext(await readFile(new URL('../assets/navigation.js',import.meta.url),'utf8'),context);
const {resolve,categories,sections} = context.window.PHDSXNavigation;
assert.equal(resolve('tools/utility/qr-generator.html').parent.href,'tools.html?category=text');
assert.equal(resolve('tools/text/json-formatter.html').parent.href,'tools.html?category=text');
assert.equal(resolve('tools/text/json-formatter.html').crumbs.at(-1).zh,'JSON 格式化');
assert.equal(resolve('tools/text/text-diff.html').parent.href,'tools.html?category=text');
assert.equal(resolve('tools/text/text-diff.html').crumbs.at(-1).zh,'文本差异比对');
assert.equal(resolve('tools/fun/lightning-calculator.html').parent.href,'tools.html?category=lifestyle');
assert.equal(resolve('games/board/junqi/index.html').parent.href,'games.html?category=board');
assert.equal(resolve('games/strategy/storm-siege/index.html').parent.href,'games.html?category=strategy');
assert.equal(resolve('games/strategy/storm-siege/index.html').crumbs.at(-1).zh,'风暴攻城');
assert.equal(resolve('games/sports/free-kick/index.html').parent.href,'games.html?category=sports');
assert.equal(resolve('games/sports/free-kick/index.html').crumbs.at(-1).zh,'弧线任意球');
assert.equal(resolve('tools.html','?category=image').parent.href,'tools.html');
assert.equal(resolve('tools.html','?category=__proto__').category,null);
assert.equal(resolve('games.html','?category=unknown').crumbs.length,2);
assert.equal(resolve('novels/reader.html','?id=zero-echo&chapter=2','第二章').parent.href,'novels/index.html#zero-echo');
assert.equal(resolve('blog-post.html','?src=content/blog/site/site-update.md','站点更新记录').crumbs.at(-1).zh,'站点更新记录');
assert.equal(resolve('').parent,null);
assert.equal(resolve('tours.html').parent.href,'index.html');
assert.equal(resolve('tours.html','?country=china').parent.href,'tours.html');
assert.equal(resolve('tours.html','?country=china&region=beijing').parent.href,'tours.html?country=china');
assert.equal(resolve('tours.html','?country=__proto__&region=beijing').country,null);
assert.equal(resolve('tours.html','?country=china&region=unknown').region,null);
assert.equal(resolve('tours.html','?region=beijing').region,null);
for (const [slug,name] of [['tiantan','天坛'],['forbidden-city','故宫'],['summer-palace','颐和园'],['xiangshan','香山'],['north-garden','国家植物园北园']]) {
  const path = `tours/china/beijing/${slug}/index.html`;
  const tour = resolve(path);
  assert.equal(tour.section,'tours.html');
  assert.equal(tour.parent.href,'tours.html?country=china&region=beijing');
  assert.equal(tour.crumbs.map(crumb => crumb.zh).join(' / '),`首页 / 3D云游 / 中国 / 北京 / ${name}`);
  await access(new URL('../'+path,import.meta.url));
}
const xining = resolve('tours/china/qinghai/xining-zoo/index.html');
assert.equal(xining.parent.href,'tours.html?country=china&region=qinghai');
assert.equal(xining.crumbs.map(crumb => crumb.zh).join(' / '),'首页 / 3D云游 / 中国 / 青海 / 西宁野生动物园');
await access(new URL('../tours/china/qinghai/xining-zoo/index.html',import.meta.url));
const pokemon = resolve('tools/lifestyle/pokemon-map/index.html');
assert.equal(pokemon.parent.href,'tools.html?category=lifestyle');
assert.equal(pokemon.crumbs.at(-1).zh,'宝可梦视野地图');
await access(new URL('../tools/lifestyle/pokemon-map/index.html',import.meta.url));
for (const section of Object.keys(sections)) await access(new URL('../'+section,import.meta.url));
for (const family of Object.keys(categories)) await access(new URL('../'+family+'.html',import.meta.url));
console.log('Navigation checks passed: root, categories, deep links, aliases, invalid queries, article and chapter parents.');
