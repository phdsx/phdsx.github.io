import { readFile, writeFile } from 'node:fs/promises';

const threeUrl = new URL('../assets/vendor/three.module.r160.js', import.meta.url);
const gameUrl = new URL('../games/classic/classic-3d.mjs', import.meta.url);
const outputUrl = new URL('../games/classic/classic-3d.bundle.js', import.meta.url);
let [three, game] = await Promise.all([readFile(threeUrl, 'utf8'), readFile(gameUrl, 'utf8')]);
const exportLine = /\nexport \{[^\n]+\};\s*$/;
if (!three.includes('SPDX-License-Identifier: MIT') || !exportLine.test(three))
  throw new Error('Three.js 模块格式发生变化，无法生成本地脚本。');
const names = [...new Set([...game.matchAll(/THREE\.([A-Za-z_][A-Za-z_0-9]*)/g)].map(match => match[1]))].sort();
three = three.replace(exportLine, `\nconst THREE = { ${names.join(', ')} };\n`);
game = game.replace(/^import .*;\r?\n/gm, '');
const bundle = `/* Generated by node scripts/build-classic-3d.mjs. Three.js r160 MIT license retained below. */\n(function () {\n'use strict';\n${three}\n${game}\n})();\n`;
await writeFile(outputUrl, bundle, 'utf8');
console.log(`Generated ${outputUrl.pathname} (${bundle.length} characters).`);
