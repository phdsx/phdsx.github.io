import { readFile, writeFile } from 'node:fs/promises';

const gameUrl = new URL('../games/sports/free-kick/game.mjs', import.meta.url);
const physicsUrl = new URL('../games/sports/free-kick/physics.mjs', import.meta.url);
const threeUrl = new URL('../assets/vendor/three.module.r160.js', import.meta.url);
const outputUrl = new URL('../games/sports/free-kick/game.bundle.js', import.meta.url);

let [three, physics, game] = await Promise.all([
  readFile(threeUrl, 'utf8'), readFile(physicsUrl, 'utf8'), readFile(gameUrl, 'utf8')
]);

const exportLine = /\nexport \{[^\n]+\};\s*$/;
if (!three.includes('SPDX-License-Identifier: MIT') || !exportLine.test(three)) {
  throw new Error('Three.js 模块格式发生变化，无法生成本地脚本。');
}

const names = [...new Set([...game.matchAll(/THREE\.([A-Za-z_][A-Za-z_0-9]*)/g)].map(match => match[1]))].sort();
three = three.replace(exportLine, `\nconst THREE = { ${names.join(', ')} };\n`);
physics = physics.replace(/^export /gm, '');
game = game.replace(/^import .*;\r?\n/gm, '');

const bundle = `/* Generated by node scripts/build-free-kick.mjs. Source: Three.js r160, physics.mjs, game.mjs. */\n(function () {\n'use strict';\n${three}\n${physics}\n${game}\n})();\n`;
await writeFile(outputUrl, bundle, 'utf8');
console.log(`已生成 ${new URL(outputUrl).pathname}（${bundle.length} 字符）。`);
