// Read-only extraction of original header fingerprints. No library data is changed.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const lib = fs.readFileSync(path.join(root, 'assets/dictionary-original.lib'));
const menus = [
  { id: 44, name: 'main', rows: 42, title: [28, 8, 103, 26], labels: [
    [6, 46, 67, 18, '新君登基'], [83, 46, 68, 18, '重返沙场'],
    [6, 71, 67, 18, '制作群组'], [83, 72, 68, 17, '卸甲归田']
  ] },
  { id: 45, name: 'period', rows: 24, title: [40, 3, 82, 17], labels: [
    [57, 26, 21, 31, '董弄|卓权'], [57, 64, 21, 30, '曹崛|操起'],
    [138, 26, 21, 31, '赤之|壁战'], [138, 64, 21, 30, '三鼎|国立']
  ] }
];
for (const menu of menus) {
  const address = lib.readUInt32LE((menu.id - 1) * 4) + 14;
  menu.width = lib.readUInt16LE(address);
  if (lib.readUInt16LE(address + 2) !== 96) throw Error('Unexpected original menu dimensions');
  menu.bits = lib.subarray(address + 7, address + 7 + Math.ceil(menu.width / 8) * menu.rows).toString('hex');
}
fs.writeFileSync(path.join(root, 'assets/menu-fingerprints.js'), '// Generated by tools/build-menu-art.cjs from the shipped original library.\nwindow.BayeMenuFingerprints = ' + JSON.stringify(menus) + ';\n');
